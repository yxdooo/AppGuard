_lang = "tr"


def set_lang(lang: str) -> None:
    global _lang
    if lang in _STRINGS:
        _lang = lang


def get_lang() -> str:
    return _lang


def t(key: str, **kwargs) -> str:
    """Return translated string, apply format arguments."""
    base = _STRINGS.get(_lang, _STRINGS["tr"])
    s = base.get(key) or _STRINGS["tr"].get(key, key)
    if kwargs:
        try:
            s = s.format(**kwargs)
        except Exception:
            pass
    return s
